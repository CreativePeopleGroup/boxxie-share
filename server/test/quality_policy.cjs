const assert = require('node:assert/strict');
const policy = require('../../web/quality-policy.js');
const auto = { automatic: true, height: 1080, maxBitrate: 8_000_000 };
assert.equal(policy.preference(auto,1080),'balanced');
assert.equal(policy.preference(auto,720),'maintain-framerate');
assert.equal(policy.preference({automatic:false},720),'balanced');
assert.equal(policy.displayHeight({width:390,height:844}),720);
assert.equal(policy.displayHeight({width:844,height:390}),720);
assert.equal(policy.displayHeight({width:820,height:1180}),1080);
assert.equal(policy.displayHeight({width:1920,height:1080}),1080);
assert.equal(policy.displayHeight({width:390,height:844,mode:'tv'}),1080);
assert.equal(policy.displayHeight({width:960,height:540,tv:true}),1080);
assert.equal(policy.limits(auto,720).maxBitrate,4_000_000);
assert.equal(policy.limits(auto,1080).maxBitrate,8_000_000);
assert.equal(policy.limits(auto,99999).height,1080);
assert.equal(policy.limits(auto,undefined).height,1080);
assert.equal(policy.limits(auto,undefined).maxBitrate,4_000_000);
assert.equal(policy.limits({...auto,height:540,maxBitrate:800_000},1080).height,540);
assert.equal(policy.limits({...auto,height:540,maxBitrate:800_000},1080).maxBitrate,800_000);
const manual={automatic:false,height:2160,maxBitrate:25_000_000};
assert.deepEqual(policy.limits(manual,720),manual);
assert.deepEqual(auto,{automatic:true,height:1080,maxBitrate:8_000_000});
console.log('PASS display selection, per-viewer budgets, legacy defaults, host caps and manual override');
